/**
 * Certification & Recognition Entry Schema
 *
 * To add a new certification or recognition entry in the future:
 * 1. Place the certificate image inside `public/images/certifications/` (JPEG, PNG, WebP, or SVG).
 * 2. Add a new object to the `company.certifications` array above:
 *    ```ts
 *    {
 *      name: 'Title of the Award or Certificate',
 *      description: 'Brief summary of the honor and context.',
 *      year: '2026',
 *      org: 'Issuing Organization Name',
 *      regNumber: 'Optional Registration or Citation Number',
 *      image: '/images/certifications/your-file-name.jpeg',
 *      published: true,
 *    }
 *    ```
 * 3. It will automatically be rendered in both the Homepage and About Us credentials timelines!
 */
export interface Certification {
  name: string;
  description: string;
  year: string;
  org: string;
  regNumber?: string;
  image?: string;
  published: boolean;
}


